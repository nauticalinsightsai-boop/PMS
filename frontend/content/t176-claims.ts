/** Map site cert family / id to compliance note for cert detail pages. */
export function getCertComplianceNote(certId: string, familyId: string): {
  alert?: string;
  body: string;
} | null {
  if (certId === 'pmp' || familyId === 'PMI') {
    return {
      alert:
        'Important: PMP is issued by PMI, not PM Structure. PM Structure provides independent exam-prep, pathway guidance, and readiness support. Candidates should verify eligibility, exam rules, and training requirements directly with PMI before applying or booking the exam.',
      body: T176_PMP_SOURCE_NOTE,
    };
  }
  if (
    familyId === 'PRINCE2' ||
    certId.startsWith('prince2') ||
    ['msp', 'mop', 'mor', 'p3o'].includes(certId)
  ) {
    return {
      body: `${T176_PRINCE2_ISSUER_NOTE}\n\n${T176_PRINCE2_DISCLAIMER}`,
    };
  }
  if (familyId === 'LSS' || certId.startsWith('lss-')) {
    return {
      body: `${T176_LSS_ISSUER_NOTE}\n\n${T176_LSS_DISCLAIMER}`,
    };
  }
  return {
    body: T176_GLOBAL_DISCLAIMER_SHORT,
  };
}
