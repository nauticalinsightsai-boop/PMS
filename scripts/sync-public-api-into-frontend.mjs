#!/usr/bin/env node
/**
 * Mount public checkout + Stripe API routes inside the marketing app so /api/*
 * works when BACKEND_URL proxy is misconfigured on Vercel.
 * Generates thin re-export stubs (same pattern as sync-admin-into-frontend.mjs).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FE = path.join(ROOT, 'frontend');
const BE = path.join(ROOT, 'backend');
const API_ROOT = path.join(FE, 'app', 'api');

/** Bundled on the marketing deployment for embedded checkout + webhooks. */
const API_BACKEND_DIRS = ['config', 'checkout', 'stripe'];

const ROUTE_FILES = new Set([
  'page.tsx',
  'page.ts',
  'layout.tsx',
  'layout.ts',
  'loading.tsx',
  'error.tsx',
  'not-found.tsx',
  'template.tsx',
  'default.tsx',
  'route.ts',
  'route.js',
]);

function rmIfExists(target) {
  if (!fs.existsSync(target)) return;
  const stat = fs.lstatSync(target);
  if (stat.isSymbolicLink() || stat.isFile()) fs.unlinkSync(target);
  else fs.rmSync(target, { recursive: true, force: true });
}

function importPath(stubFile, sourceFile) {
  const withoutExt = sourceFile.replace(/\.(tsx?|jsx?|mjs|cjs)$/, '');
  const rel = path.relative(path.dirname(stubFile), withoutExt).split(path.sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

function writeReExportStub(stubFile, sourceFile) {
  const base = path.basename(sourceFile);
  const from = importPath(stubFile, sourceFile);
  const content =
    base === 'route.ts' || base === 'route.js'
      ? `/** Auto-generated by scripts/sync-public-api-into-frontend.mjs: do not edit */\nexport * from '${from}';\n`
      : `/** Auto-generated by scripts/sync-public-api-into-frontend.mjs: do not edit */\nexport { default } from '${from}';\nexport * from '${from}';\n`;

  fs.mkdirSync(path.dirname(stubFile), { recursive: true });
  fs.writeFileSync(stubFile, content);
}

function walkRouteFiles(dir, onFile) {
  if (!fs.existsSync(dir)) return;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) walkRouteFiles(full, onFile);
    else if (ROUTE_FILES.has(ent.name)) onFile(full);
  }
}

function syncRouteTree(srcRoot, destRoot) {
  walkRouteFiles(srcRoot, (srcFile) => {
    const rel = path.relative(srcRoot, srcFile);
    writeReExportStub(path.join(destRoot, rel), srcFile);
  });
}

function main() {
  fs.mkdirSync(API_ROOT, { recursive: true });

  for (const dir of API_BACKEND_DIRS) {
    const dest = path.join(API_ROOT, dir);
    rmIfExists(dest);
    const src = path.join(BE, 'app', 'api', dir);
    if (!fs.existsSync(src)) {
      console.warn(`Skipping missing backend API path: ${src}`);
      continue;
    }
    syncRouteTree(src, dest);
  }

  console.log('Synced public API routes → frontend/app/api/ (re-export stubs)');
}

main();
