import fs from 'fs';
import { newsletterDraftRegistry } from '../../packages/site-content/src/newsletter-draft-registry.ts';
import { getNewsletterHeroManifest } from '../../packages/site-content/src/newsletter-hero-manifest.ts';

const manifest = getNewsletterHeroManifest();
const bySlug = new Map(manifest.articles.map((a) => [a.slug, a]));
let updated = 0;
for (const post of newsletterDraftRegistry.posts) {
  const hero = bySlug.get(post.slug);
  if (!hero) continue;
  post.featuredImageUrl = hero.image;
  post.heroImageAlt = hero.alt;
  if (post.editorMeta?.rawNotes?.includes('Hero image pending')) {
    post.editorMeta.rawNotes = post.editorMeta.rawNotes.replace(
      'Hero image pending',
      'Hero image mapped 2026-07-26 WebP',
    );
  }
  updated += 1;
}
if (updated !== 13) {
  console.error('expected 13 updates, got', updated);
  process.exit(1);
}
const out = `/**
 * Newsletter Draft Registry
 *
 * All 13 consolidated newsletter drafts imported from markdown sources.
 * Generated by scripts/newsletter/import-drafts.mjs
 * Hero image/alt fields synchronized to packages/site-content/data/newsletter-hero-manifest-2026-07-26.json.
 */

import type { NewsletterPostsRegistry } from './newsletter-posts';

export const newsletterDraftRegistry: NewsletterPostsRegistry = ${JSON.stringify(newsletterDraftRegistry, null, 2)};
`;
fs.writeFileSync('packages/site-content/src/newsletter-draft-registry.ts', `${out}\n`);
console.log('updated draft registry heroes', updated);
