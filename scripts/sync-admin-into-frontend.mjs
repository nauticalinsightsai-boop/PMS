#!/usr/bin/env node
/**
 * Mount dashboard UI + API inside the marketing app for single-Vercel deployment.
 * Generates thin re-export stubs (symlinks are not picked up by the App Router).
 * Run before `next dev` / `next build` in frontend (see frontend/package.json).
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FE = path.join(ROOT, 'frontend');
const ADMIN = path.join(FE, 'app', 'admin');
const DASH_FE = path.join(ROOT, 'dashboard', 'frontend');
const DASH_BE = path.join(ROOT, 'dashboard', 'backend');

const UI_ROOTS = [
  { name: 'login', src: path.join(DASH_FE, 'app', 'login') },
  { name: 'dashboard', src: path.join(DASH_FE, 'app', 'dashboard') },
];

const API_BACKEND_DIRS = ['auth', 'cms', 'admin', 'interactions', 'profile'];

const ROUTE_FILES = new Set([
  'page.tsx',
  'page.ts',
  'layout.tsx',
  'layout.ts',
  'loading.tsx',
  'error.tsx',
  'not-found.tsx',
  'template.tsx',
  'default.tsx',
  'route.ts',
  'route.js',
]);

function sleepSync(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

function rmIfExists(target) {
  if (!fs.existsSync(target)) return true;
  const maxAttempts = 8;
  for (let attempt = 1; attempt <= maxAttempts; attempt += 1) {
    try {
      const stat = fs.lstatSync(target);
      if (stat.isSymbolicLink() || stat.isFile()) fs.unlinkSync(target);
      else fs.rmSync(target, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
      return true;
    } catch (err) {
      const code = err && err.code;
      const retryable = code === 'ENOTEMPTY' || code === 'EBUSY' || code === 'EPERM' || code === 'EINVAL';
      if (!retryable || attempt === maxAttempts) break;
      sleepSync(100 * attempt);
    }
  }
  // Google Drive often blocks delete but allows rename.
  try {
    const trash = `${target}.__gdrive_trash_${Date.now()}`;
    fs.renameSync(target, trash);
    console.warn(`Moved locked path aside: ${path.basename(trash)}`);
    return true;
  } catch (err) {
    console.warn(`Could not clear ${target} (${err.code || err.message}); continuing with overwrite sync.`);
    return false;
  }
}

function importPath(stubFile, sourceFile) {
  const withoutExt = sourceFile.replace(/\.(tsx?|jsx?|mjs|cjs)$/, '');
  const rel = path.relative(path.dirname(stubFile), withoutExt).split(path.sep).join('/');
  return rel.startsWith('.') ? rel : `./${rel}`;
}

function writeReExportStub(stubFile, sourceFile) {
  const base = path.basename(sourceFile);
  const from = importPath(stubFile, sourceFile);
  const content =
    base === 'route.ts' || base === 'route.js'
      ? `/** Auto-generated by scripts/sync-admin-into-frontend.mjs: do not edit */\nexport * from '${from}';\n`
      : `/** Auto-generated by scripts/sync-admin-into-frontend.mjs: do not edit */\nexport { default } from '${from}';\nexport * from '${from}';\n`;

  const dir = path.dirname(stubFile);
  for (let attempt = 1; attempt <= 6; attempt += 1) {
    try {
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(stubFile, content);
      return;
    } catch (err) {
      const code = err && err.code;
      // Google Drive ghost paths: skip individual stubs rather than fail the whole build.
      if (code === 'EINVAL' && attempt === 6) {
        console.warn(`Skipping stub (filesystem ghost): ${path.relative(FE, stubFile)}`);
        return;
      }
      const retryable = code === 'ENOTEMPTY' || code === 'EBUSY' || code === 'EPERM' || code === 'EINVAL';
      if (!retryable || attempt === 6) throw err;
      sleepSync(150 * attempt);
    }
  }
}

function walkRouteFiles(dir, onFile) {
  if (!fs.existsSync(dir)) return;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) walkRouteFiles(full, onFile);
    else if (ROUTE_FILES.has(ent.name)) onFile(full);
  }
}

function syncRouteTree(srcRoot, destRoot) {
  walkRouteFiles(srcRoot, (srcFile) => {
    const rel = path.relative(srcRoot, srcFile);
    writeReExportStub(path.join(destRoot, rel), srcFile);
  });
}

function main() {
  fs.mkdirSync(ADMIN, { recursive: true });

  for (const { name, src } of UI_ROOTS) {
    if (!fs.existsSync(src)) {
      console.error(`Missing dashboard UI path: ${src}`);
      process.exit(1);
    }
    const dest = path.join(ADMIN, name);
    // Overwrite stubs in place. Full deletes are unreliable on Google Drive (ENOTEMPTY/ghost paths).
    syncRouteTree(src, dest);
  }

  const adminApi = path.join(ADMIN, 'api');
  fs.mkdirSync(adminApi, { recursive: true });

  for (const dir of API_BACKEND_DIRS) {
    const src = path.join(DASH_BE, 'app', 'api', dir);
    if (!fs.existsSync(src)) continue;
    syncRouteTree(src, path.join(adminApi, dir));
  }

  const channelApi = path.join(DASH_FE, 'app', 'api', 'channel-landing-pages');
  if (fs.existsSync(channelApi)) {
    syncRouteTree(channelApi, path.join(adminApi, 'channel-landing-pages'));
  }

  console.log('Synced admin routes → frontend/app/admin/ (re-export stubs)');
}

main();